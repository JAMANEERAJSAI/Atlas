"""
===============================================================================
DNA OF ATLAS
VOLUME VI — THE DECISION ENGINE
Founder Transfer Handbook
Version 1.0
===============================================================================

PURPOSE
-------

This volume defines how ATLAS should think before suggesting any trade.

The Decision Engine does not predict.
It evaluates.

Its job is to answer one question:

"Given everything currently observable, is taking this trade better than
doing nothing?"

===============================================================================
CHAPTER 1 — NO TRADE IS A VALID DECISION
===============================================================================

The previous project failed partly because HOLD became meaningless.

ATLAS changes that philosophy.

There are only two acceptable situations:

1. No edge exists.
2. Edge exists.

"No Trade" must be an intentional recommendation backed by evidence,
not a fallback because the model lacks confidence.

===============================================================================
CHAPTER 2 — OPPORTUNITY RANKING
===============================================================================

The engine should rank opportunities rather than emit binary signals.

Example

1. NIFTY ATM CALL ..... 82/100
2. BANKNIFTY ATM PUT .. 74/100
3. No other setups.

This gives the trader context instead of commands.

===============================================================================
CHAPTER 3 — EXPLAIN FIRST
===============================================================================

Every recommendation answers:

Why now?

What changed?

What increased confidence?

What reduced confidence?

What invalidates this trade?

===============================================================================
CHAPTER 4 — RISK BEFORE REWARD
===============================================================================

The engine should reject trades for reasons including:

Poor liquidity.

Extreme spreads.

Event uncertainty.

Insufficient expected reward.

A rejected trade is often more valuable than an accepted one.

===============================================================================
CHAPTER 5 — CONFIDENCE IS COMPOSITE
===============================================================================

Confidence should eventually combine evidence from multiple sources.

Examples:

Market structure.

Momentum.

Liquidity.

Volatility.

Historical similarity.

No single feature owns confidence.

===============================================================================
CHAPTER 6 — HUMAN EXPERIENCE
===============================================================================

ATLAS should reduce cognitive load.

The trader should understand the situation in seconds.

If the interface requires reading paragraphs during a fast market,
the design has failed.

===============================================================================
CHAPTER 7 — ARCHIVE EVERYTHING
===============================================================================

Every recommendation should be frozen.

Later the system asks:

Was it correct?

If not,

why not?

The archive becomes future training data.

===============================================================================
CHAPTER 8 — FAILURE ANALYSIS
===============================================================================

Every losing recommendation should be classified.

Wrong direction?

Correct direction but poor timing?

IV collapse?

Execution delay?

Unknown?

Learning begins after classification.

===============================================================================
CHAPTER 9 — EVOLUTION
===============================================================================

The Decision Engine should become more conservative when uncertainty rises.

Confidence should shrink before losses force it to.

Trust grows from honesty.

===============================================================================
CHAPTER 10 — FINAL PRINCIPLE
===============================================================================

ATLAS should never try to convince the trader.

It should present evidence.

The trader remains responsible.

END OF VOLUME VI
"""
