"""
===============================================================================
DNA OF ATLAS
VOLUME IX — ATLAS STUDIO (UI / UX BIBLE)
Founder Transfer Handbook
Version 1.0
===============================================================================

PURPOSE
-------

ATLAS Studio is not decoration.

It exists to reduce thinking time.

The interface should communicate complex market information faster than
the human brain can gather it from multiple screens.

===============================================================================
CHAPTER 1 — DESIGN PHILOSOPHY
===============================================================================

The UI serves one purpose:

Help the trader make better decisions.

Everything that does not contribute to that goal is a distraction.

===============================================================================
CHAPTER 2 — DARK BY DEFAULT
===============================================================================

Theme:

Dark.

Accent colors only when information deserves attention.

Green = Positive.

Red = Risk / Warning.

Yellow = Caution.

Blue = Neutral information.

Avoid unnecessary animation.

===============================================================================
CHAPTER 3 — INFORMATION HIERARCHY
===============================================================================

The trader should identify within two seconds:

• Best opportunity.
• Market regime.
• Confidence.
• Risk.
• Why confidence changed.

Everything else becomes secondary panels.

===============================================================================
CHAPTER 4 — NO INFORMATION OVERLOAD
===============================================================================

Do not display every indicator.

Display conclusions.

Allow drilling into details only when requested.

===============================================================================
CHAPTER 5 — ALERTS
===============================================================================

Alerts should be meaningful.

Never flash the screen because one indicator crossed.

Alert only when the Decision Engine detects a significant opportunity
or a major change in confidence.

===============================================================================
CHAPTER 6 — EXPLAINABILITY PANEL
===============================================================================

Every recommendation includes:

Reason.

Supporting evidence.

Contradicting evidence.

Confidence.

Risk.

Expected holding window.

===============================================================================
CHAPTER 7 — CHARTS
===============================================================================

The price chart remains the primary visualization.

Experimental overlays such as forecast cones or projected paths must
be visually distinct from historical prices.

Predictions should never masquerade as facts.

===============================================================================
CHAPTER 8 — DESKTOP WORKFLOW
===============================================================================

The founder's intended workflow:

Primary monitor:
    Coding / Work.

Secondary monitor:
    ATLAS Studio.

The application should remain glanceable.

===============================================================================
CHAPTER 9 — PERFORMANCE
===============================================================================

UI lag destroys trust.

Rendering should never block market analysis.

Data processing and visualization remain separate processes.

===============================================================================
CHAPTER 10 — FINAL PRINCIPLE
===============================================================================

A beautiful interface without a proven edge is cosmetic.

A simple interface with trustworthy information is valuable.

The UI exists to expose intelligence—not replace it.

END OF VOLUME IX
"""
