"""
===============================================================================
DNA OF ATLAS
VOLUME XXI — THE EVOLUTION BIBLE
Founder Transfer Handbook
Version 1.0
===============================================================================

PURPOSE
-------

No architecture remains optimal forever.

This volume explains how ATLAS should evolve without losing its identity.

===============================================================================
CHAPTER 1 — EVOLUTION IS EXPECTED
===============================================================================

Every subsystem is replaceable.

No implementation is sacred.

Only the core principles deserve long-term protection.

===============================================================================
CHAPTER 2 — WHEN TO ADD A MODULE
===============================================================================

A new module should exist only if:

1. A measurable problem exists.
2. Existing modules cannot solve it cleanly.
3. The added complexity is justified.

Otherwise, improve what already exists.

===============================================================================
CHAPTER 3 — WHEN TO REMOVE A MODULE
===============================================================================

A module should be retired if:

It duplicates functionality.

It has no measurable benefit.

It increases maintenance more than value.

Deletion is sometimes progress.

===============================================================================
CHAPTER 4 — BACKWARD COMPATIBILITY
===============================================================================

Whenever practical:

Old experiments should remain reproducible.

Old datasets should remain readable.

Old reports should remain interpretable.

History is valuable.

===============================================================================
CHAPTER 5 — VERSION PHILOSOPHY
===============================================================================

Major Version:

Architecture changed.

Minor Version:

Capability improved.

Patch:

Bug fixed.

Version numbers should communicate meaning.

===============================================================================
CHAPTER 6 — RESEARCH NEVER STOPS
===============================================================================

Even after deployment:

Continue asking questions.

Continue collecting evidence.

Continue challenging assumptions.

ATLAS is a living research system.

===============================================================================
CHAPTER 7 — AVOID FEATURE CREEP
===============================================================================

Every new feature creates future maintenance.

Ask:

"What existing problem disappears because of this feature?"

If no answer exists,

do not build it.

===============================================================================
CHAPTER 8 — SIMPLICITY WINS
===============================================================================

Given two systems with equal performance,

prefer the simpler one.

Simplicity scales.

Complexity compounds.

===============================================================================
CHAPTER 9 — THE NEXT GENERATION
===============================================================================

Future contributors should improve ATLAS,
not preserve every historical implementation.

Preserve knowledge.

Replace technology when appropriate.

===============================================================================
CHAPTER 10 — FINAL PRINCIPLE
===============================================================================

ATLAS should evolve continuously,

but its evolution must always be guided by
evidence rather than enthusiasm.

END OF VOLUME XXI
"""
